"""Builds client/catalogue.lua: weapon record -> class (Power / Tech / Smart / Blade / Blunt)
and item type, from the game's TweakDB as extracted into the Open77 repository
(docs/generated/weapons-2.31.csv). Open77.data.weapon() on the client gives the localized
name and, best effort, the item type, but not the weapon class: this table fills that in.

Usage: python tools/gen_catalogue.py <path to weapons-2.31.csv>
"""
import csv
import sys
from pathlib import Path

CLASSES = {"WeaponEvolution.Power": "P", "WeaponEvolution.Tech": "T", "WeaponEvolution.Smart": "S",
           "WeaponEvolution.Blade": "B", "WeaponEvolution.Blunt": "U"}

def main(src):
    rows = list(csv.DictReader(open(src, encoding="utf-8-sig")))
    out = {}
    for r in rows:
        if r["equip_area"] != "EquipmentArea.Weapon":
            continue
        cls = CLASSES.get(r["evolution"])
        if not cls or not r["record"].startswith("Items."):
            continue
        kind = r["item_type"].replace("ItemType.Wea_", "") if r["item_type"].startswith("ItemType.Wea_") else ""
        out[r["record"]] = cls + kind
    dest = Path(__file__).resolve().parent.parent / "client" / "catalogue.lua"
    lines = ["-- Generated by tools/gen_catalogue.py from the game's TweakDB (weapons-2.31.csv): do not edit.",
             "-- record -> class letter (P power, T tech, S smart, B blade, U blunt) followed by the item type.",
             "WeaponHudCatalogue = {"]
    for record in sorted(out):
        lines.append('["%s"]="%s",' % (record, out[record]))
    lines.append("}")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(dest, len(out), dest.stat().st_size)

if __name__ == "__main__":
    main(sys.argv[1])

#!/usr/bin/env python3
"""Writes shared/maps/<mode>.lua from a settings.json export. Run once per mode, from the
resource root: python3 tools/gen_maps.py <settings.json> <section> <key> <mode> [point...]

    python3 tools/gen_maps.py settings.json pvp MAPS_tdm tdm
    python3 tools/gen_maps.py settings.json pvp MAPS_redlight redlight finish:required timeLimit
    python3 tools/gen_maps.py settings.json pvp MAPS_control control redSpawn:spawn blueSpawn:spawn point:centre
    python3 tools/gen_maps.py settings.json pvp MAPS_ctf ctf redBase:spawn blueBase:spawn redSpawns:list blueSpawns:list
    python3 tools/gen_maps.py settings.json prophunt MAPS prophunt propsSpawn:home huntersSpawn:spawn hideSeconds offer=a,b

Keeps enabled maps with real coordinates: at least 2 spawns off 0,0,0, every `name:required`
point placed. A bare extra name is copied when present (a point or a number). `name:spawn` is a
required point that also joins the spawn list, `name:centre` one that joins the play area's
centre only, `name:home` a spawn that alone is the centre, `name:list` a list of points, copied
when it holds any. `offer=slug,slug` picks the maps offered, in that order (8 at most); the other
usable maps stay in the data as GamesMaps.<mode>Spare. The podium and the doll are never read.
The output is plain data: nothing at runtime needs this file or settings.json.
"""
import json
import re
import sys
from pathlib import Path

MAX_MAPS = 8  # activityRegister keeps 8 choices


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def placed(point):
    return isinstance(point, dict) and any(abs(point.get(k) or 0) > 0.001 for k in "xyz")


def number(value):
    text = f"{round(float(value), 3):.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def point(p, heading=True):
    parts = [f"{k} = {number(p[k])}" for k in "xyz"]
    if heading and p.get("heading") is not None:
        parts.append(f"heading = {number(p['heading'])}")
    return "{ " + ", ".join(parts) + " }"


def centre(points):
    return {k: sum(p[k] for p in points) / len(points) for k in "xyz"}


def spawns_of(raw, extras):
    listed = raw.get("spawns") if isinstance(raw.get("spawns"), list) else []
    named = [raw.get(e.split(":")[0]) for e in extras if e.endswith((":spawn", ":home"))]
    return [p for p in listed + named if placed(p)]


def lua_map(raw, extras):
    name = raw["name"]
    spawns = spawns_of(raw, extras)
    homes = [raw[e.split(":")[0]] for e in extras if e.endswith(":home")]
    middle = homes or spawns + [raw[e.split(":")[0]] for e in extras if e.endswith(":centre")]
    lines = [f'    {{ id = "{slug(name)}", name = {json.dumps(name)}, radius = {number(raw.get("radius") or 80)},',
             f"      centre = {point(centre(middle), False)},"]
    for extra in extras:
        key = extra.split(":")[0]
        value = raw.get(key)
        if extra.endswith(":list"):
            spots = [p for p in value if placed(p)] if isinstance(value, list) else []
            if spots:
                lines.append(f"      {key} = {{ " + ", ".join(point(p) for p in spots) + " },")
        elif isinstance(value, dict) and placed(value):
            lines.append(f"      {key} = {point(value)},")
        elif isinstance(value, (int, float)):
            lines.append(f"      {key} = {number(value)},")
    lines.append("      spawns = {")
    lines += [f"        {point(p)}," for p in spawns]
    lines += ["      } },"]
    return "\n".join(lines)


def usable(raw, extras):
    if raw.get("enabled") is not True or not raw.get("name") or len(spawns_of(raw, extras)) < 2:
        return False
    return all(placed(raw.get(e.split(":")[0])) for e in extras if e.endswith((":required", ":spawn", ":centre", ":home")))


def main():
    settings, section, key, mode, *extras = sys.argv[1:]
    data = json.loads(Path(settings).read_text())[section][key]
    offer = [e[len("offer="):].split(",") for e in extras if e.startswith("offer=")]
    extras = [e for e in extras if not e.startswith("offer=")]
    maps = [m for m in (data if isinstance(data, list) else []) if usable(m, extras)]
    spare = []
    if offer:
        by_slug = {slug(m["name"]): m for m in maps}
        offered = [by_slug[name] for name in offer[0]]
        spare = [m for m in maps if m not in offered]
        maps = offered
    maps = maps[:MAX_MAPS]
    body = "\n".join(lua_map(m, extras) for m in maps)
    text = (f"-- {mode} maps. Generated by tools/gen_maps.py: plain data, edit by hand or regenerate.\n"
            f"GamesMaps = GamesMaps or {{}}\nGamesMaps.{mode} = {{\n{body}\n}}\n")
    if spare:
        rest = "\n".join(lua_map(m, extras) for m in spare)
        text += f"-- Usable, not offered: activityRegister keeps 8 choices.\nGamesMaps.{mode}Spare = {{\n{rest}\n}}\n"
    Path(f"shared/maps/{mode}.lua").write_text(text)
    print(f"shared/maps/{mode}.lua: {len(maps)} map(s), {len(spare)} spare")


if __name__ == "__main__":
    main()

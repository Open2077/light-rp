"""The rules data of every base card, from the NetDeck card API behind cyberpunktcg.com.

Usage: fetch_rules.py <resource dir>
Writes shared/cards.lua (TcgCards, server + client) and web/data/cards.js (window.TCG_CARDS, the binder), keyed by
the catalogue's base-card slug (`card` in shared/catalogue.lua): name, subtitle, type, cost, power, RAM value and
colour, tags, sell tag, keywords and the official rules text. See docs/RULES.md for what these mean.
"""
import json
import pathlib
import re
import sys
import time
import unicodedata
import urllib.request

API = "https://api.netdeck.gg/api/cards/cyberpunk"
UA = {"User-Agent": "op77-tcg-asset-build/1.0"}
res = pathlib.Path(sys.argv[1])


def get(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return json.loads(r.read().decode("utf-8"))
        except Exception:
            if attempt == 3:
                raise
            time.sleep(1.5 * (attempt + 1))


def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]", "", s.lower())


catalogue = (res / "shared/catalogue.lua").read_text(encoding="utf-8")
ours = {}
for card, name in re.findall(r'card = "([^"]+)", number = \d+, name = "((?:[^"\\]|\\.)*)"', catalogue):
    ours.setdefault(card, name)
print(len(ours), "base cards in the catalogue")

site, offset = [], 0
while True:
    page = get(f"{API}?offset={offset}&limit=60")
    site += page["items"]
    offset += len(page["items"])
    if not page["items"] or offset >= page["total"]:
        break
by_name = {}
for c in site:
    for key in (c.get("canonical_name"), c.get("display_name"), c.get("name") + (c.get("subname") or "")):
        if key:
            by_name.setdefault(norm(key), c)

KEYWORDS = ["Play", "Attack", "Call", "Defeated", "Adrenaline", "Blocker", "Go Solo", "Quick", "Spend"]
cards, missing = {}, []
for slug, name in sorted(ours.items()):
    c = by_name.get(norm(name))
    if not c:
        missing.append(name)
        continue
    text = (c.get("rules_text") or "").strip()
    keys = sorted({k for k in KEYWORDS if "{" + k + "}" in text or "{" + k.lower() + "}" in text.lower()})
    cards[slug] = {
        "name": c["name"], "subtitle": c.get("subname") or "", "type": c["card_type"],
        "cost": c.get("cost"), "power": c.get("power"), "ram": c.get("ram"), "color": c.get("color"),
        "tags": c.get("classifications") or [], "sell": bool(c.get("is_eddiable")), "keywords": keys,
        "text": text, "slug": c["slug"],
    }
print(len(cards), "cards with rules data; missing:", missing)


def lua(v):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


lines = [
    "-- Generated by tools/fetch_rules.py from the NetDeck card API (cyberpunktcg.com). Do not edit by hand.",
    "-- One entry per base card, keyed by the catalogue's `card` slug. type: Legend | Unit | Gear | Program;",
    "-- cost (nil = null cost), power (nil for Programs), ram + color (the RAM symbol), tags, sell (Sell Tag),",
    "-- keywords (Play, Attack, Call, Defeated, Adrenaline, Blocker, Go Solo, Quick, Spend), text (official rules text).",
    "TcgCards = {",
]
for slug, c in cards.items():
    fields = ", ".join(f"{k} = {lua(c[k])}" for k in ("name", "subtitle", "type", "cost", "power", "ram", "color", "tags", "sell", "keywords", "text"))
    lines.append(f"    [{lua(slug)}] = {{ {fields} }},")
lines.append("}")
(res / "shared/cards.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
(res / "web/data/cards.js").write_text("window.TCG_CARDS = " + json.dumps(cards, ensure_ascii=False, separators=(",", ":")) + ";\n",
                                        encoding="utf-8", newline="\n")
types = {}
for c in cards.values():
    types[c["type"]] = types.get(c["type"], 0) + 1
print("types:", types)

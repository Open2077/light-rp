"""Emit the catalogue the resource ships: shared/catalogue.lua (server + client) and web/data/catalogue.js (binder).

Input: the catalogue.json written by build_catalogue.py. Usage: emit_catalogue.py <catalogue.json> <resource dir>
"""
import json
import pathlib
import sys

src, res = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
cards = json.loads(src.read_text(encoding="utf-8"))["cards"]


def lua(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "-- Generated by tools/emit_catalogue.py from the Cyberpunk TCG Collectibles metadata. Do not edit by hand.",
    "-- One entry per edition: id (content hash + finish initial), card (base card slug), number (set order),",
    "-- name, tier (1 Common, 2 Uncommon, 3 Rare, 4 Epic, 5 Nova Rare / Iconic, 6 Secret), rarity (label),",
    "-- finish (sleeved | foil | premium | metal), booster (false = Secret: printer only), entity (3D card).",
    "TcgCatalogue = {",
]
for c in cards:
    fields = [("id", c["id"]), ("card", c["card"]), ("number", c["number"]), ("name", c["name"]), ("tier", c["tier"]),
              ("rarity", c["rarity"]), ("finish", c["finish"]), ("booster", c["inBoosters"]), ("entity", c["entity"])]
    lines.append("    { " + ", ".join(f"{k} = {lua(v)}" for k, v in fields) + " },")
lines.append("}")
(res / "shared/catalogue.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

web = [{"id": c["id"], "card": c["card"], "n": c["number"], "name": c["name"], "tier": c["tier"], "rarity": c["rarity"],
        "finish": c["finish"], "booster": c["inBoosters"]} for c in cards]
(res / "web/data").mkdir(parents=True, exist_ok=True)
# The page loads it as a script: no fetch of a local file from the WebUI (it never answered in game).
(res / "web/data/catalogue.js").write_text("window.TCG_CATALOGUE = " + json.dumps(web, ensure_ascii=False, separators=(",", ":"))
                                           + ";" + chr(10), encoding="utf-8")
print(len(cards), "editions emitted")

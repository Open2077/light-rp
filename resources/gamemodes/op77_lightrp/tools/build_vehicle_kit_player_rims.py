"""Generate server/config/vehicle_kit_player_rims.lua from the player rim fit table.

The Open77 repository measures the rim fit of every vanilla player vehicle the dealer
table (vehicle_kit.lua, from specs/lightrp-rims-fit.json) does not name:
scripts/vehicle-kit/player-rim-fit.cjs writes specs/lightrp-rims-fit-player.json. This
script turns it into LightRpVehicleKitPlayerRims, a record -> fit table in the
registerParts shape of vehicle_kit.lua's rimFit (same `wheels` rule, build_vehicle_kit.py
rim_fit), which the Auto Studio merges into every rim part under the dealer fits (a record
both tables name keeps vehicle_kit.lua's).

Per-appearance entries (`appearances`) come through only where the fit table registers
them (records whose spawned appearance is not fixed). An entry's `wheels` replaces the
record's whole list, so an entry on a record that has a `wheels` list always carries its
own full list (each wheel then takes the entry's offset and scale unless it lists its own).

Kept apart from vehicle_kit.lua on purpose: that file is regenerated by the body kit and
rims work alike, this one only by the player fit table. Lua only: no model is copied here.

    python tools/build_vehicle_kit_player_rims.py \
        --rims <open77>/scripts/vehicle-kit/specs/lightrp-rims-fit-player.json
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'server' / 'config' / 'vehicle_kit_player_rims.lua'
# The registerParts marshaller (LuaResourceRuntime.ReadLuaValue) takes 4096 values per call
# and the studio registers one rim per call with every record's fit: the dealer fits and
# their trims use about 1600 of them. Refuse a table that would leave no room.
PLAYER_VALUE_BUDGET = 2200
# Quest variants of a player vehicle (records named Vehicle.q<digits>_*, such as
# Vehicle.q000_hym_player_car) are out of the customization extension by the owner's
# decision of 2026-11-07: the fit table never names them, and this script refuses one that does.
QUEST = re.compile(r'^Vehicle\.q\d+_')

spec = importlib.util.spec_from_file_location('build_vehicle_kit', Path(__file__).with_name('build_vehicle_kit.py'))
kit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kit)


def sha_lf(path: Path) -> str:
    """sha256 (12 hex) of the text with LF line ends: the committed file's, whatever the checkout."""
    return hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest()[:12]


def values(x) -> int:
    """Values the marshaller counts: every table and every leaf (keys are free)."""
    if isinstance(x, dict):
        return 1 + sum(values(v) for v in x.values())
    if isinstance(x, list):
        return 1 + sum(values(v) for v in x)
    return 1


def player_fit(record: str, fit: dict) -> dict:
    base = {k: v for k, v in fit.items() if k != 'appearances'}
    out = kit.rim_fit(record, base)
    entries = {}
    for appearance, entry in sorted((fit.get('appearances') or {}).items()):
        own = dict(entry)
        if 'slotNames' not in own and base.get('slotNames'):
            own['slotNames'] = base['slotNames']
        converted = kit.rim_fit(record, own)
        if 'wheels' in out and 'wheels' not in converted:
            converted['wheels'] = [{'slot': w['slot']} for w in out['wheels']]
        entries[appearance] = converted
    if entries:
        out['appearances'] = entries
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--rims', type=Path, required=True, help='scripts/vehicle-kit/specs/lightrp-rims-fit-player.json')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()

    src = json.loads(args.rims.read_text(encoding='utf-8'))
    if src.get('schema') != 'open77.vehicle-kit.rim-fit/1':
        raise SystemExit(f'{args.rims}: not a rim fit table')
    dealer = set((src.get('extends') or {}).get('records') or [])
    for record in [*src['fit'], *(src.get('excluded') or {})]:
        if QUEST.match(record):
            raise SystemExit(f'{record}: a quest variant, out of the customization extension (owner decision, 2026-11-07)')
    fits = {}
    for record in sorted(src['fit']):
        if record in dealer:
            raise SystemExit(f'{record}: already in the dealer table, never repeated here')
        fits[record] = player_fit(record, src['fit'][record])
    total = values(fits)
    if total > PLAYER_VALUE_BUDGET:
        raise SystemExit(f'player fits take {total} marshaller values, over the {PLAYER_VALUE_BUDGET} budget')
    ext = src.get('extends') or {}
    lines = [
        '-- GENERATED by tools/build_vehicle_kit_player_rims.py -- do not edit: re-run the generator.',
        f'-- Rims: {args.rims.name} sha256 {sha_lf(args.rims)} ({src.get("schema")}, game {src.get("gameVersion")}),',
        f'-- beside {ext.get("file", "?")} sha256 {ext.get("sha256", "?")} (vehicle_kit.lua): its records are never repeated here.',
        '-- Every vanilla Vehicle.*_player* record (cars and motorcycles) the dealer table does not',
        '-- name, fitted on the appearance a spawned car wears; per-appearance entries only where',
        '-- that appearance is not fixed. Every offset is an OFFLINE ESTIMATE from mesh data until',
        f'-- seen in game. {len(fits)} records, {total} marshaller values. The Auto Studio merges these',
        '-- fits into every rim part under the dealer fits (server/modules/vehicle_customization.lua).',
        'LightRpVehicleKitPlayerRims = {',
        '    generator = 1,',
        '    fit = ' + kit.lua(fits, 1) + ',',
        '    excluded = ' + kit.lua(dict(sorted((src.get('excluded') or {}).items())), 1) + ',',
        '}',
    ]
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'wrote {args.output} ({len(fits)} records, {total} values, {len(src.get("excluded") or {})} excluded)')


if __name__ == '__main__':
    main()

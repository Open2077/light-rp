-- Server-only: an operator edits this file and restarts the resource, no page
-- rebuild. English.
--
-- Writing answers
--   * Every fact comes from the code and config of this branch. Quote numbers,
--     prices, places and keys through placeholders, never by hand, so they follow
--     the config: {cfg:config.economy.payRange}, {money:config.fuel.pricePerLitre},
--     {sec:medical.giveUpDelayMs}, {min:delivery.lifetimeMs}, {pct:medical.reviveHealth},
--     {key:inventory} (the player's own key), {v:carRange}, and "{list:foodPrices}"
--     alone on a line for one bullet per entry. The full list is at the top of
--     server/modules/guide.lua.
--   * Page markup: `code`, **bold**, a line "- " is a bullet, "1. " a step, "> " a tip.
--   * `say` is Johnny's line above the answer: flavour only, the answer stays clear.
--   * `follow` names other questions (any topic) offered under the answer.
--   * `actions`: { type = "gps", target = "<kind>" } marks the nearest place of that
--     kind on the map (kinds: Guide.targets in the module); the others are page
--     buttons: activities (tab = "activities" | "contracts" | "crew"), jobguide,
--     housing, support, animations, tutorial, briefing.
--   * `requires` hides a topic, question or action until it is met (see the module):
--     features are named in `features` below. One line of an answer follows a rule
--     the same way: `{ requires = "config:economy.hospital.bill", "the line" }`
--     ("config:" is off when the value is nil, false or 0).
--   * Never name a staff-only command: tests/guide_test.lua fails on one.
--   * Keep one question small: a topic travels in messages of at most 800 values.

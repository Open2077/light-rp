-- The Titan HUD's drawing surface: what the CET overlay's ImGui background draw list was to the author's controller.
-- The environment binds this module as `render` (controller/open77_titan_env.lua) and the Titan frame
-- (open77_titan_bridge.lua: frame) wraps the controller's drawing in beginFrame()/endFrame().
--
--   render.init() -> true | nil, reason     create the HUD page (idempotent); beginFrame() also does it, and retries
--                                           every 2 s, until destroy() is called
--   render.destroy()                        destroy the page; nothing is drawn or revived afterwards
--   render.beginFrame()                     start this frame's batch
--   render.endFrame()                       send the batch
--   render.size() -> w, h                   the drawing space: the game picture's size in pixels
--   render.line(x1, y1, x2, y2, color, thickness)
--   render.rect(x1, y1, x2, y2, color, rounding, thickness, filled)
--   render.circle(x, y, radius, color, segments, thickness, filled)
--   render.triangle(x1, y1, x2, y2, x3, y3, color, thickness, filled)
--   render.text(x, y, color, text, size)    (x, y) is the top-left of the text's line box
--   render.textSize(text, size) -> w, h     what text() lays out, exactly
--   render.lineHeight(size) -> h            the height of one line of text
--   render.state(tbl | nil)                 the DOM panels' state (open77_titan_hud.lua); nil clears them
--   render.toggleHints() -> shown           show or hide the control hints; answers whether they are shown now
--
-- Colours are ImGui's packed ABGR integers (0xAABBGGRR, GetColorU32 in the environment); alpha 0 draws nothing.
-- thickness defaults to 1, rounding to 0, filled to false (an outline), segments to 0 (smooth), size to the default
-- size. It is all ImGui's draw list: lines have butt caps and sit half a pixel off their points, outlines are stroked
-- half a pixel inside their box, a circle's outline half a pixel inside its radius, a circle below half a pixel is not
-- drawn. `size` is the height of the text's line box (ImGui's font size): the default is 18 px at 1920x1080 and grows
-- with the picture (the controller's own default, FPF.lineH); lineHeight(size) is size, and a newline in a text starts
-- a line that much lower.
--
-- The page (ui/hud.html) is one transparent canvas on the "hud" layer. It is passive: it never takes focus. A frame
-- is ONE string sent with the event "hud:frame" (the host reads a payload as at most 1024 values, so a table per
-- primitive would not fit; a string is one value of up to 64 KiB): a header with the drawing space, then one line per
-- primitive (the format is documented in ui/hud.js). A batch holds at most MAX_PRIMITIVES primitives and MAX_BYTES
-- bytes; the excess is dropped, with one log line. Only the newest frame is sent, and only when it differs from the
-- last one the page was given: a frame with nothing in it clears the page once.
--
-- Beside the canvas the page has DOM panels (ui/hud_panel.js): the PROTOCOLS lamps, the control hints, the notices and the carry's
-- prompt (the hull, the weapon, the abilities and the core are LightRP's HUD's, which reads them from the `hudState` export).
-- render.state(tbl) hands the page its state, one table in the event "hud:state" (at most 1024 values in all;
-- open77_titan_hud.lua builds a few hundred at most). The state is kept until the page has it and sent again when the page
-- reloads; render.state(nil) clears the panels. Every state carries `hints`, the control
-- hints' switch (on, until render.toggleHints() turns it off).
--
-- The display size is what Open77.screen.surface() reports: the game's back buffer, the same picture CET's
-- GetDisplayResolution() measured. That call needs the manifest permission screen.capture (it only reads the size, it
-- captures nothing; it is called every SIZE_EVERY seconds, not per frame). Without the permission, or before the first
-- frame was presented, render.size() raises and nothing is drawn.
--
-- Text metrics are exact: ui/hud_font.lua holds the advance of every glyph of the shipped font
-- (ui/chakra-petch-500-latin.woff2; the metrics were generated by Open77's scripts/titans/generate_hud_font.py) and the page draws each glyph
-- at the pen position that table gives. A code point the font lacks is measured and drawn as "?"; control characters
-- other than newline have no glyph and no width.

local FONT = require("ui.hud_font")

local M = {}

local PAGE = "ui/hud.html"
local FRAME_EVENT = "hud:frame"
local STATE_EVENT = "hud:state"
local CLEARED = { on = false }
local READY_EVENT = "ui:ready"

local MAX_PRIMITIVES = 1024
local MAX_BYTES = 48 * 1024      -- of primitives; a string payload is at most 64 KiB
local MAX_TEXT_BYTES = 1024      -- one text; a longer one is dropped like any excess
local SIZE_EVERY = 0.5           -- seconds between reads of the display size
local RETRY_EVERY = 2.0          -- seconds between attempts to create the page
local LIMIT = 1.0e6              -- pixels; coordinates beyond are clamped (a line is clipped to the picture first)
local BASE_SIZE = 18.0           -- the text size at 1920x1080

local floor, tointeger = math.floor, math.tointeger
local format, find, gsub, concat = string.format, string.find, string.gsub, table.concat
local codes, ulen = utf8.codes, utf8.len

local ADVANCE = FONT.advance
local LINE_UNITS = FONT.ascent - FONT.descent
local QUESTION = ADVANCE[0x3F]
local ESCAPE = { ["\\"] = "\\\\", ["\n"] = "\\n" }

-- The display size: the drawing space, once known; `header` is the first line of every frame.
local width, height, header
local sizeAt = 0.0
local sizeWhy = "not read yet"
local sizeLogged = false

-- The page: `loaded` once its document announced itself (only then can it be sent anything); `running` is nil before
-- anything asked for the page, true while it is wanted and false after destroy().
local page, loaded, running = nil, false, nil
local retryAt = 0.0
local createWhy, fontLogged, sendLogged

-- The batch: buffer[1] is the header, buffer[2 .. count + 1] the primitives, reused every frame. `lastSent` is the
-- frame the page shows.
local recording = false
local count, bytes, over = 0, 0, 0
local buffer = {}
local lastSent
local capLogged = false

-- The DOM state (see "the DOM state"): the table the page should show, whether it still has to be sent, whether the control
-- hints are switched off, and whether a refused send was said.
local wanted, stateDirty, hintsOff, stateLogged = nil, false, false, false

local function clock() return Open77.time.monotonic() end

local function log(level, message) Open77.log[level]("[titans] HUD: " .. message) end

-- ---- the display size ------------------------------------------------------------------------------------------

local function readSize(now)
  sizeAt = now + SIZE_EVERY
  local surface, why = Open77.screen.surface()
  if surface and surface.ready and surface.width > 0 and surface.height > 0 then
    if surface.width ~= width or surface.height ~= height then
      width, height = surface.width, surface.height
      header = format("%d %d", width, height)
    end
    sizeWhy = nil
    return
  end
  sizeWhy = why or "surface_not_ready"
  -- A permission or host refusal does not go away; a surface that is not ready yet does.
  if surface == nil and width == nil and not sizeLogged then
    sizeLogged = true
    log("error", "the display size is not available (" .. tostring(why) .. "): Open77.screen.surface needs the manifest permission screen.capture; nothing is drawn")
  end
end

function M.size()
  if width == nil then
    local now = clock()
    if now >= sizeAt then readSize(now) end
    if width == nil then error("render.size: the display size is not available (" .. tostring(sizeWhy) .. ")", 2) end
  end
  return width, height
end

-- ---- text metrics ----------------------------------------------------------------------------------------------

local function defaultSize()
  local w, h = M.size()
  local scale = w / 1920.0
  local other = h / 1080.0
  if other < scale then scale = other end
  return BASE_SIZE * scale
end

local function checkedSize(size)
  if size == nil then return defaultSize() end
  if type(size) ~= "number" or not (size > 0) or size > 10000 then error("render: size must be a number above 0", 3) end
  return size
end

-- A string the page can show: numbers are spelled out and invalid UTF-8 loses its high bytes.
local function clean(text)
  if type(text) ~= "string" then text = tostring(text) end
  if ulen(text) == nil then text = gsub(text, "[\128-\255]", "?") end
  return text
end

function M.textSize(text, size)
  text = clean(text)
  size = checkedSize(size)
  local widest, line, lines = 0, 0, 1
  for _, cp in codes(text) do
    if cp == 10 then
      if line > widest then widest = line end
      line = 0
      lines = lines + 1
    elseif cp >= 32 and (cp < 127 or cp > 159) then
      line = line + (ADVANCE[cp] or QUESTION)
    end
  end
  if line > widest then widest = line end
  return widest * (size / LINE_UNITS), lines * size
end

function M.lineHeight(size)
  return checkedSize(size)
end

-- ---- the page --------------------------------------------------------------------------------------------------

local function onReady(info)
  loaded, lastSent, stateDirty = true, nil, wanted ~= nil
  if type(info) == "table" and info.font == false and not fontLogged then
    fontLogged = true
    log("warn", "the page could not load ui/chakra-petch-500-latin.woff2: text is drawn in a fallback face, laid out as if it were the font")
  end
end

function M.init()
  if page then return true end
  running = true
  local created, why = Open77.webui.create({
    entry = PAGE, layer = "hud", transparent = true, visible = true,
    width = 1920, height = 1080, fps = 60, policy = "strict",
  })
  if not created then
    retryAt = clock() + RETRY_EVERY
    if why ~= createWhy then
      createWhy = why
      log("warn", "the page cannot be created yet (" .. tostring(why) .. "); trying again")
    end
    return nil, why
  end
  page, loaded, lastSent = created, false, nil
  createWhy, fontLogged, sendLogged, capLogged = nil, false, false, false
  page:on(READY_EVENT, onReady)
  return true
end

function M.destroy()
  running, recording, loaded, lastSent = false, false, false, nil
  wanted, stateDirty = nil, false
  if page then
    local handle = page
    page = nil
    pcall(handle.destroy, handle)
  end
end

-- ---- the DOM state ---------------------------------------------------------------------------------------------

-- What the page shows besides the canvas (open77_titan_hud.lua builds it, ui/hud_panel.js draws it) is ONE table sent with the
-- event "hud:state". `wanted` is the state the page should have (nil: the cleared page, { on = false }); `stateDirty` is set by
-- a new state, by the hints switch and by a page that (re)loaded, and cleared by a send the page took, so a state asked for
-- before the page is up, or one a send refused, goes out as soon as it can.
local function flushState()
  if not stateDirty or page == nil or not loaded then return end
  local payload = CLEARED
  if wanted ~= nil then
    payload = {}
    for key, value in pairs(wanted) do payload[key] = value end
    payload.hints = not hintsOff
  end
  local ok, sent = pcall(page.send, page, STATE_EVENT, payload)
  if ok and sent then
    stateDirty = false
    return
  end
  if not ok and not stateLogged then
    stateLogged = true
    log("warn", "the state could not be sent to the page: " .. tostring(sent))
  end
end

function M.state(state)
  if state ~= nil and type(state) ~= "table" then error("render.state: a table or nil", 2) end
  wanted, stateDirty = state, true
  flushState()
end

function M.toggleHints()
  hintsOff = not hintsOff
  stateDirty = wanted ~= nil
  flushState()
  return not hintsOff
end

-- ---- the batch -------------------------------------------------------------------------------------------------

function M.beginFrame()
  local now = clock()
  if page == nil and running ~= false and now >= retryAt then M.init() end
  if now >= sizeAt then readSize(now) end
  count, bytes, over = 0, 0, 0
  recording = loaded and width ~= nil
  if recording then buffer[1] = header end
end

local function push(piece)
  local cost = #piece + 1
  if count >= MAX_PRIMITIVES or bytes + cost > MAX_BYTES then
    over = over + 1
    return
  end
  count = count + 1
  buffer[count + 1] = piece
  bytes = bytes + cost
end

function M.endFrame()
  flushState()
  if not recording or page == nil then
    recording = false
    return
  end
  recording = false
  if over > 0 and not capLogged then
    capLogged = true
    log("warn", format("a frame held more than %d primitives or %d bytes: the excess (%d in this frame) is dropped; this is said once",
      MAX_PRIMITIVES, MAX_BYTES, over))
  end
  local frame = concat(buffer, "\n", 1, count + 1)
  if frame == lastSent then return end
  local ok, sent = pcall(page.send, page, FRAME_EVENT, frame)
  if ok and sent then
    lastSent = frame
    return
  end
  lastSent = nil
  if not ok and not sendLogged then
    sendLogged = true
    log("warn", "a frame could not be sent to the page: " .. tostring(sent))
  end
end

-- ---- primitives ------------------------------------------------------------------------------------------------

-- ImGui's colour is 0xAABBGGRR; the page reads it back the same way. nil: not a colour, or fully transparent.
local function pack(color)
  local value = tointeger(color)
  if value == nil then
    value = tointeger(floor(color))
    if value == nil then return nil end
  end
  value = value & 0xFFFFFFFF
  if value < 0x1000000 then return nil end
  return value
end

local function clamped(v)
  if v > LIMIT then return LIMIT end
  if v < -LIMIT then return -LIMIT end
  return v
end

-- Tenths of a pixel, the page's unit.
local function tenths(v) return floor(v * 10 + 0.5) end

-- The thickness and its tenths (at least one, a line has to be drawn with some width), or nil: nothing to draw.
local function stroke(thickness)
  local t = thickness or 1.0
  if not (t > 0) then return nil end
  if t > 4000 then t = 4000 end
  local q = tenths(t)
  return t, q < 1 and 1 or q
end

local function edge(p, q, t0, t1)
  if p == 0 then
    if q < 0 then return nil end
    return t0, t1
  end
  local r = q / p
  if p < 0 then
    if r > t1 then return nil end
    if r > t0 then t0 = r end
  else
    if r < t0 then return nil end
    if r < t1 then t1 = r end
  end
  return t0, t1
end

-- Liang-Barsky: the part of the segment inside the box, or nil. A tracer starting a hand's breadth from the camera
-- projects to coordinates in the millions; the page gets the visible part, with the true slope.
local function clip(x1, y1, x2, y2, xmin, ymin, xmax, ymax)
  local dx, dy = x2 - x1, y2 - y1
  local t0, t1 = edge(-dx, x1 - xmin, 0.0, 1.0)
  if not t0 then return nil end
  t0, t1 = edge(dx, xmax - x1, t0, t1)
  if not t0 then return nil end
  t0, t1 = edge(-dy, y1 - ymin, t0, t1)
  if not t0 then return nil end
  t0, t1 = edge(dy, ymax - y1, t0, t1)
  if not t0 then return nil end
  return x1 + t0 * dx, y1 + t0 * dy, x1 + t1 * dx, y1 + t1 * dy
end

function M.line(x1, y1, x2, y2, color, thickness)
  if not recording then return end
  local c = pack(color)
  if c == nil then return end
  local t, tq = stroke(thickness)
  if t == nil or x1 ~= x1 or y1 ~= y1 or x2 ~= x2 or y2 ~= y2 then return end
  local pad = t + 1
  local ax, ay, bx, by = clip(clamped(x1), clamped(y1), clamped(x2), clamped(y2), -pad, -pad, width + pad, height + pad)
  if ax == nil then return end
  push(format("L%d %d %d %d %x %d", tenths(ax), tenths(ay), tenths(bx), tenths(by), c, tq))
end

function M.rect(x1, y1, x2, y2, color, rounding, thickness, filled)
  if not recording then return end
  local c = pack(color)
  if c == nil then return end
  local t, tq = stroke(thickness)
  if t == nil or x1 ~= x1 or y1 ~= y1 or x2 ~= x2 or y2 ~= y2 then return end
  if x1 > x2 then x1, x2 = x2, x1 end
  if y1 > y2 then y1, y2 = y2, y1 end
  local pad = filled and 0 or t
  if x2 < -pad or y2 < -pad or x1 > width + pad or y1 > height + pad then return end
  local r = rounding or 0.0
  if not (r > 0) then r = 0 elseif r > 100000 then r = 100000 end
  push(format("R%d %d %d %d %x %d %d %d", tenths(clamped(x1)), tenths(clamped(y1)), tenths(clamped(x2)), tenths(clamped(y2)),
    c, tenths(r), tq, filled and 1 or 0))
end

function M.circle(x, y, radius, color, segments, thickness, filled)
  if not recording then return end
  local c = pack(color)
  if c == nil then return end
  local t, tq = stroke(thickness)
  if t == nil or x ~= x or y ~= y or not (radius >= 0.5) then return end
  if radius > LIMIT then radius = LIMIT end
  local pad = radius + (filled and 0 or t)
  if x + pad < 0 or y + pad < 0 or x - pad > width or y - pad > height then return end
  local n = 0
  if segments and segments > 0 then
    n = floor(segments)
    if n < 3 then n = 3 elseif n > 512 then n = 512 end
  end
  push(format("C%d %d %d %x %d %d %d", tenths(clamped(x)), tenths(clamped(y)), tenths(radius), c, n, tq, filled and 1 or 0))
end

function M.triangle(x1, y1, x2, y2, x3, y3, color, thickness, filled)
  if not recording then return end
  local c = pack(color)
  if c == nil then return end
  local t, tq = stroke(thickness)
  if t == nil or x1 ~= x1 or y1 ~= y1 or x2 ~= x2 or y2 ~= y2 or x3 ~= x3 or y3 ~= y3 then return end
  local pad = filled and 0 or t
  if (x1 < -pad and x2 < -pad and x3 < -pad) or (y1 < -pad and y2 < -pad and y3 < -pad)
    or (x1 > width + pad and x2 > width + pad and x3 > width + pad)
    or (y1 > height + pad and y2 > height + pad and y3 > height + pad) then return end
  push(format("P%d %d %d %d %d %d %x %d %d", tenths(clamped(x1)), tenths(clamped(y1)), tenths(clamped(x2)), tenths(clamped(y2)),
    tenths(clamped(x3)), tenths(clamped(y3)), c, tq, filled and 1 or 0))
end

function M.text(x, y, color, text, size)
  if not recording then return end
  local c = pack(color)
  if c == nil or x ~= x or y ~= y then return end
  text = clean(text)
  if text == "" then return end
  if #text > MAX_TEXT_BYTES then
    over = over + 1
    return
  end
  size = checkedSize(size)
  if x >= width or y >= height then return end
  if find(text, "[\\\n]") then text = gsub(text, "[\\\n]", ESCAPE) end
  push(format("T%d %d %x %d %s", tenths(clamped(x)), tenths(clamped(y)), c, tenths(size), text))
end

return M

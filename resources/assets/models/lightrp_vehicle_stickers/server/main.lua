-- Light RP vehicle stickers (DRAFT): which stickers fit which dealer model, and what each one
-- draws. The records come from this resource's preload_mod (TweakXL):
--   Vehicle.o77_st_<model>_<hash>          one decal: our .ent (vanilla sticker mesh) on a component
--   Vehicle.o77_sticker_st_<model>_<name>  one sticker: its customDecals list the decal records
-- The server owns the choice (setStickers, wave 2 natives) and the budget: 12 decals per car at
-- most, livery included; 13 crash every client that spawns the car. A sticker's `decals` counts
-- its own decals; summing them over a car's stickers never under-counts (two stickers of a model
-- may share a decal, the client draws it once).
-- Generated by scripts/vehicle-kit/stickers/build-stickers.ps1 from stickers/lua/stickers_main.lua.
local TAG = '[lightrp_vehicle_stickers]'
local Catalogue = LightRpVehicleStickers
local byId, byModel = {}, {}
local decalTotal = {}

for _, sticker in ipairs(Catalogue.stickers) do
    assert(not byId[sticker.id], 'duplicate sticker ' .. sticker.id)
    assert(sticker.decals == #sticker.parts and sticker.decals >= 1
        and sticker.decals <= Catalogue.maxDecalsPerSticker, 'bad decal count on ' .. sticker.id)
    byId[sticker.id] = sticker
    byModel[sticker.model] = byModel[sticker.model] or {}
    table.insert(byModel[sticker.model], sticker)
    for _, part in ipairs(sticker.parts) do decalTotal[part.record] = true end
end

-- The dealer record of a car at any stage or engine sound (wave 2 suffixes), or nil.
local function modelOf(record)
    if type(record) ~= 'string' then return nil end
    if byModel[record] then return record end
    local base = record:gsub('_o77s%d+a%d+$', ''):gsub('_o77a%d+$', ''):gsub('_o77s%d+$', '')
    return byModel[base] and base or nil
end

local function row(sticker)
    return { id = sticker.id, label = sticker.label, group = sticker.group, decals = sticker.decals }
end

-- stickersFor(record) -> { { id, label, group, decals } ... } for the record's model ({} if none).
exports('stickersFor', function(record)
    local out = {}
    for _, sticker in ipairs(byModel[modelOf(record)] or {}) do out[#out + 1] = row(sticker) end
    return out
end)

-- sticker(id) -> { id, label, group, model, decals, record, parts = { { record, component, decal } } } | nil, reason
exports('sticker', function(id)
    local s = byId[id]
    if not s then return nil, 'unknown_sticker' end
    local parts = {}
    for i, p in ipairs(s.parts) do parts[i] = { record = p.record, component = p.component, decal = p.decal } end
    return { id = s.id, label = s.label, group = s.group, model = s.model, decals = s.decals, record = s.record, parts = parts }
end)

-- check(record, { stickerId ... }, liveryDecals) -> used decals | nil, reason. Used = the livery's
-- decals plus the sum of the stickers' (the server-side rule); reasons: unknown_model,
-- unknown_sticker, wrong_model, duplicate_sticker, over_budget.
local function check(record, ids, liveryDecals)
    local model = modelOf(record)
    if not model then return nil, 'unknown_model' end
    local used, seen = math.tointeger(liveryDecals or 0) or 0, {}
    for _, id in ipairs(ids or {}) do
        local s = byId[id]
        if not s then return nil, 'unknown_sticker' end
        if s.model ~= model then return nil, 'wrong_model' end
        if seen[id] then return nil, 'duplicate_sticker' end
        seen[id] = true
        used = used + s.decals
    end
    if used > Catalogue.maxDecalsPerCar then return nil, 'over_budget' end
    return used
end
exports('check', check)

-- decalsOf({ stickerId ... }) -> { { record, component, decal } ... }: the union, each decal once,
-- in sticker order (route A's list, or route B's records). nil, 'unknown_sticker' on a bad id.
exports('decalsOf', function(ids)
    local out, seen = {}, {}
    for _, id in ipairs(ids or {}) do
        local s = byId[id]
        if not s then return nil, 'unknown_sticker' end
        for _, p in ipairs(s.parts) do
            if not seen[p.record] then
                seen[p.record] = true
                out[#out + 1] = { record = p.record, component = p.component, decal = p.decal }
            end
        end
    end
    return out
end)

-- The wave-2 server learns the stickers from this call (PLAN-vehicle-custom-wave2.md, W2.4):
-- contract rows { id, label, group, model, decals }, plus the holder record and the decals the
-- client draws. A server that refuses the extra fields gets the contract rows alone.
local function registerStickers()
    if type(Open77.vehicles.registerStickers) ~= 'function' then
        print(TAG .. ' Open77.vehicles.registerStickers is missing on this server: the stickers wait for the wave-2 natives')
        return
    end
    local full, bare = {}, {}
    for i, s in ipairs(Catalogue.stickers) do
        local parts = {}
        for j, p in ipairs(s.parts) do parts[j] = { record = p.record, component = p.component, decal = p.decal } end
        bare[i] = { id = s.id, label = s.label, group = s.group, model = s.model, decals = s.decals }
        full[i] = { id = s.id, label = s.label, group = s.group, model = s.model, decals = s.decals,
                    record = s.record, parts = parts }
    end
    local ok, why = Open77.vehicles.registerStickers(full)
    if not ok and (tostring(why):find('.record', 1, true) or tostring(why):find('.parts', 1, true)) then
        print(TAG .. ' registerStickers refused the extra fields (' .. tostring(why) .. '): contract rows only')
        ok, why = Open77.vehicles.registerStickers(bare)
    end
    print(('%s registerStickers: %s %s'):format(TAG, tostring(ok), tostring(why or '')))
end

local function reply(player, raw, ok, text)
    print(TAG .. ' ' .. text)
    if player and player > 0 then TriggerClientEvent('open77:command:result', player, raw or '', ok == true, text) end
    return ok
end

local function vehicleFor(player, explicit)
    if explicit then
        local id = tonumber(explicit)
        if id and Open77.vehicles.get(id) then return id end
        return nil, 'no vehicle ' .. tostring(explicit)
    end
    local seat = Open77.vehicles.getPlayerSeat(player)
    if seat and seat.vehicleId and Open77.vehicles.get(seat.vehicleId) then return seat.vehicleId end
    return nil, 'sit in a car or pass its id'
end

-- Lab command (restricted, server ACL command.sticker): /sticker list|clear|<sticker id> [vehicleId].
-- Adds the sticker to the car's set through the wave-2 natives; the server keeps the budget.
RegisterCommand('sticker', function(player, args, raw)
    local verb = args[1] or 'list'
    local vehicle, why = vehicleFor(player, args[2])
    if not vehicle then return reply(player, raw, false, why) end
    local record = Open77.vehicles.get(vehicle).record
    local model = modelOf(record)
    if not model then return reply(player, raw, false, tostring(record) .. ' has no stickers in this pack') end
    local v = Open77.vehicles
    if verb == 'list' then
        local names = {}
        for _, s in ipairs(byModel[model]) do names[#names + 1] = ('%s "%s" (%d)'):format(s.id, s.label, s.decals) end
        local current = type(v.getStickers) == 'function' and v.getStickers(vehicle) or nil
        local budget = ''
        if type(v.getDecalBudget) == 'function' then
            local used, max = v.getDecalBudget(vehicle)
            budget = (' budget %s/%s;'):format(tostring(used), tostring(max))
        end
        return reply(player, raw, true, ('%s: on it %s;%s choices: %s'):format(record,
            current and table.concat(current, ',') or 'none', budget, table.concat(names, ', ')))
    end
    if type(v.setStickers) ~= 'function' then
        return reply(player, raw, false, 'Open77.vehicles.setStickers is missing: the wave-2 natives are not on this server')
    end
    if verb == 'clear' then
        local ok, reason = v.setStickers(vehicle, nil)
        return reply(player, raw, ok, ok and 'stickers cleared' or ('setStickers: ' .. tostring(reason)))
    end
    if not byId[verb] then return reply(player, raw, false, 'unknown sticker ' .. verb) end
    local ids = {}
    for _, id in ipairs((type(v.getStickers) == 'function' and v.getStickers(vehicle)) or {}) do
        if id ~= verb then ids[#ids + 1] = id end
    end
    ids[#ids + 1] = verb
    local ok, reason = v.setStickers(vehicle, ids)
    return reply(player, raw, ok, ok and ('stickers ' .. table.concat(ids, ',')) or ('setStickers: ' .. tostring(reason)))
end, true)

AddEventHandler('onResourceStart', function(resource)
    if resource ~= GetCurrentResourceName() then return end
    local models, decals = 0, 0
    for _ in pairs(byModel) do models = models + 1 end
    for _ in pairs(decalTotal) do decals = decals + 1 end
    print(('%s %d stickers on %d models, %d decal records (revision %s)'):format(
        TAG, #Catalogue.stickers, models, decals, Catalogue.revision))
    registerStickers()
end)

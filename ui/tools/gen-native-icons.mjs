// Lucide glyphs for the NativeUI HUD: one SVG path string per icon.
//
//   node tools/gen-native-icons.mjs        (from ui/, after npm install)
//
// The WebUI page draws Lucide through React (src/design/components/Icon.tsx). A NativeUI
// document has <path d="..."> only, so every glyph the page knows is flattened here into a
// single path (circles, rects, lines and polylines become path commands) and written to
// resources/gamemodes/op77_lightrp/client/native/icons.lua. All glyphs are 24 x 24,
// stroke-only: draw them with class "ic" (ui/native/lightrp.rcss).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const iconSource = readFileSync(resolve(here, "../src/design/components/Icon.tsx"), "utf8");
const table = iconSource.slice(iconSource.indexOf("const GLYPHS"), iconSource.indexOf("};", iconSource.indexOf("const GLYPHS")));
const names = new Set();
for (const match of table.matchAll(/(?:"([a-z0-9-]+)"|\b([a-z][a-z0-9]*))\s*:/g)) names.add(match[1] ?? match[2]);
// glyphs only the native HUD uses
for (const extra of ["chevron-up", "chevron-down", "circle", "volume-2", "map", "star", "target", "heart", "bell", "megaphone", "locate", "door-open", "hourglass", "check", "minus", "dumbbell", "music", "sword", "bomb", "shield-check", "shield-plus", "arrow-up", "rotate-cw", "circle-dot"]) names.add(extra);

const n = (v) => Number(v);
const f = (v) => String(Math.round(v * 1000) / 1000);
function circle(cx, cy, r) {
  return `M${f(cx - r)} ${f(cy)}a${f(r)} ${f(r)} 0 1 0 ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-2 * r)} 0z`;
}
function rect(x, y, w, h, rx, ry) {
  rx = Math.min(rx ?? ry ?? 0, w / 2); ry = Math.min(ry ?? rx, h / 2);
  if (!rx || !ry) return `M${f(x)} ${f(y)}h${f(w)}v${f(h)}h${f(-w)}z`;
  return `M${f(x + rx)} ${f(y)}h${f(w - 2 * rx)}a${f(rx)} ${f(ry)} 0 0 1 ${f(rx)} ${f(ry)}v${f(h - 2 * ry)}a${f(rx)} ${f(ry)} 0 0 1 ${f(-rx)} ${f(ry)}h${f(-(w - 2 * rx))}a${f(rx)} ${f(ry)} 0 0 1 ${f(-rx)} ${f(-ry)}v${f(-(h - 2 * ry))}a${f(rx)} ${f(ry)} 0 0 1 ${f(rx)} ${f(-ry)}z`;
}
function points(text, close) {
  const v = text.trim().split(/[\s,]+/).map(Number);
  let d = "";
  for (let i = 0; i + 1 < v.length; i += 2) d += `${i ? "L" : "M"}${f(v[i])} ${f(v[i + 1])}`;
  return d + (close ? "z" : "");
}
// A node is drawn on its own: its leading relative "m" becomes an absolute "M". The pairs
// that follow an "m" are implicit relative linetos, so they keep an explicit "l".
function absoluteStart(d) {
  const m = /^\s*m\s*/.exec(d);
  if (!m) return d;
  const rest = d.slice(m[0].length);
  const num = /[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/gi;
  const first = num.exec(rest); if (!first) return d;
  const second = num.exec(rest); if (!second) return d;
  const after = rest.slice(num.lastIndex);
  const tail = /^\s*,?\s*[-+.\d]/.test(after) ? "l" + after.replace(/^\s*,?\s*/, "") : after;
  return `M${first[0]} ${second[0]}${tail}`;
}
function flatten(nodes) {
  return nodes.map(([tag, a]) => {
    switch (tag) {
      // a node starts at its own origin: its leading "m" is absolute, whatever came before it
      case "path": return absoluteStart(a.d);
      case "circle": return circle(n(a.cx), n(a.cy), n(a.r));
      case "ellipse": return `M${f(n(a.cx) - n(a.rx))} ${f(n(a.cy))}a${f(n(a.rx))} ${f(n(a.ry))} 0 1 0 ${f(2 * n(a.rx))} 0a${f(n(a.rx))} ${f(n(a.ry))} 0 1 0 ${f(-2 * n(a.rx))} 0z`;
      case "line": return `M${f(n(a.x1))} ${f(n(a.y1))}L${f(n(a.x2))} ${f(n(a.y2))}`;
      case "rect": return rect(n(a.x ?? 0), n(a.y ?? 0), n(a.width), n(a.height), a.rx === undefined ? undefined : n(a.rx), a.ry === undefined ? undefined : n(a.ry));
      case "polyline": return points(a.points, false);
      case "polygon": return points(a.points, true);
      default: throw new Error("unknown node " + tag);
    }
  }).join("");
}

const iconsDir = resolve(here, "../node_modules/lucide-react/dist/esm/icons");
const out = [];
const missing = [];
for (const name of [...names].sort()) {
  let source;
  try { source = readFileSync(resolve(iconsDir, name + ".js"), "utf8"); }
  catch { missing.push(name); continue; }
  const start = source.indexOf("[", source.indexOf("__iconNode ="));
  const end = source.indexOf("];", start) + 1;
  const nodes = Function(`return ${source.slice(start, end)}`)();
  out.push(`    ["${name}"] = "${flatten(nodes)}",`);
}
if (missing.length) console.warn("not in this Lucide build:", missing.join(", "));
const lua = `-- Generated by ui/tools/gen-native-icons.mjs from Lucide (ISC): do not edit.
-- One 24 x 24 stroke path per glyph of the page's icon set, for NativeUI <path class="ic">.
LightRpIcons = {
${out.join("\n")}
}
`;
const target = resolve(here, "../../resources/gamemodes/op77_lightrp/client/native/icons.lua");
writeFileSync(target, lua);
console.log(`${out.length} icons -> ${target}`);

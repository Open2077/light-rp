#!/usr/bin/env python3
"""Builds the HUD lab: a client resource that draws op77_lightrp's NativeUI HUD from scenes.

    python tools/native-lab/build.py --out <dir>          -> <dir>/lrp_hudlab
    python tools/native-lab/build.py --install <game dir> -> <game>/red4ext/plugins/Open77/bootstrap/lrp_hudlab
    python tools/native-lab/build.py --remove <game dir>

The lab is the real client/native modules and ui/native documents, a stub of the pieces
of the framework they read (lab/stubs.lua) and the scenes of tools/native-lab/scenes.
It needs no server: a resource in the client's bootstrap folder starts with the debug
bridge (`resource.start lrp_hudlab`), and a scene plays with `resource.emit hudlab:<name>`.
Remove it after use: the bootstrap folder belongs to the installed client.
"""
import argparse
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
MODE = REPO / 'resources' / 'gamemodes' / 'op77_lightrp'


def native_scripts():
    """The client/native scripts in the manifest's own order (host first)."""
    manifest = (MODE / 'open77.lua').read_text(encoding='utf-8')
    return re.findall(r'^client_script "(client/native/[^"]+)"', manifest, flags=re.M)


def build(out: Path) -> Path:
    target = out / 'lrp_hudlab'
    if target.exists():
        shutil.rmtree(target)
    (target / 'lab').mkdir(parents=True)
    shutil.copytree(MODE / 'client' / 'native', target / 'client' / 'native')
    shutil.copytree(MODE / 'ui' / 'native', target / 'ui' / 'native')
    (target / 'shared').mkdir()
    shutil.copy2(MODE / 'shared' / 'events.lua', target / 'shared' / 'events.lua')
    for name in ('stubs.lua', 'driver.lua'):
        shutil.copy2(HERE / 'lab' / name, target / 'lab' / name)
    scenes = sorted((HERE / 'scenes').glob('*.lua'))
    (target / 'scenes').mkdir()
    for scene in scenes:
        shutil.copy2(scene, target / 'scenes' / scene.name)
    # pictures the documents load from the page's tree
    for part in ('items', 'medical'):
        images = MODE / 'web' / 'img' / part
        if images.is_dir():
            shutil.copytree(images, target / 'web' / 'img' / part)
    natives = native_scripts()
    # written but not loaded by the game mode yet (see open77.lua): the lab is where they are tried
    natives += [f'client/native/{n}' for n in ('medical.lua',) if f'client/native/{n}' not in natives and (MODE / 'client' / 'native' / n).is_file()]
    scripts = ['shared/events.lua', 'lab/stubs.lua'] + natives + ['lab/driver.lua'] + [f'scenes/{s.name}' for s in scenes]
    lines = ['-- Generated by tools/native-lab/build.py: the Light RP HUD lab. Not a server resource.',
             'resource "lrp_hudlab"', 'version "0.0.0"', 'open77_version ">=0.0.1"', 'reload_policy "local"', '']
    lines += [f'client_script "{s}"' for s in scripts]
    lines += ['', 'files { "ui/native/*.rml", "ui/native/*.rcss", "ui/native/fonts/*", "web/img/**" }',
              'permissions { "local.events", "input.actions", "camera.read", "ui.debug" }', '']
    (target / 'open77.lua').write_text('\n'.join(lines), encoding='utf-8')
    return target


def build_standalone(out: Path, name: str) -> Path:
    """A standalone UI resource's lab: tools/native-lab/standalone/<name>/lab.json names the
    resource folder, the scripts to load (in order) and the files to declare; its scenes are
    tools/native-lab/standalone/<name>/*.lua. The resource's own tree is copied as is."""
    import json
    spec_dir = HERE / 'standalone' / name
    spec = json.loads((spec_dir / 'lab.json').read_text(encoding='utf-8'))
    source = REPO / spec['resource']
    target = out / f'lab_{name}'
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns('tests', 'server', '*.md'))
    (target / 'lab').mkdir()
    shutil.copy2(HERE / 'lab' / 'driver_standalone.lua', target / 'lab' / 'driver_standalone.lua')
    scenes = sorted(spec_dir.glob('*.lua'))
    for scene in scenes:
        shutil.copy2(scene, target / 'lab' / scene.name)
    scripts = ['lab/driver_standalone.lua'] + list(spec['scripts']) + [f'lab/{s.name}' for s in scenes]
    files = ', '.join(f'"{f}"' for f in spec.get('files', ['ui/*.rml', 'ui/*.rcss', 'ui/fonts/*']))
    permissions = ', '.join(f'"{x}"' for x in ['local.events', 'ui.debug'] + list(spec.get('permissions', [])))
    lines = [f'-- Generated by tools/native-lab/build.py: the lab of {spec["resource"]}. Not a server resource.',
             f'resource "lab_{name}"', 'version "0.0.0"', 'open77_version ">=0.0.1"', 'reload_policy "local"', '']
    lines += [f'client_script "{s}"' for s in scripts]
    lines += ['', f'files {{ {files} }}', f'permissions {{ {permissions} }}', '']
    (target / 'open77.lua').write_text(chr(10).join(lines), encoding='utf-8')
    return target


def bootstrap(game: Path) -> Path:
    path = game / 'red4ext' / 'plugins' / 'Open77' / 'bootstrap'
    if not path.is_dir():
        raise SystemExit(f'no client bootstrap folder at {path}')
    return path


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--out', type=Path)
    p.add_argument('--install', type=Path, metavar='GAME')
    p.add_argument('--remove', type=Path, metavar='GAME')
    p.add_argument('--standalone', metavar='NAME', help='build the lab of a standalone UI resource (tools/native-lab/standalone/NAME) instead')
    a = p.parse_args()
    if a.remove:
        for target in sorted(bootstrap(a.remove).glob('lab_*')) + [bootstrap(a.remove) / 'lrp_hudlab']:
            if target.is_dir() and (target.name == 'lrp_hudlab' or target.name.startswith('lab_')):
                shutil.rmtree(target)
                print('removed', target)
        return
    make = (lambda out: build_standalone(out, a.standalone)) if a.standalone else build
    if a.install:
        print('installed', make(bootstrap(a.install)))
    elif a.out:
        print('built', make(a.out))
    else:
        p.error('give --out, --install or --remove')


if __name__ == '__main__':
    main()
